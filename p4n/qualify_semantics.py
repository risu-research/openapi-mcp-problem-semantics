"""P4-N cross-check the unmodified RISU CLI against exact source/actual MCP wire.

This adjudicates only case-specific facts explicitly grounded in the frozen
third-party JPO schema; it is NOT a generic semantic equivalence oracle.
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parent
PIN=json.loads((ROOT/"FROZEN_SOURCES.json").read_text())

def qualify(root):
    cases=[]
    for name in ("normal","logical_not_found"):
        config=PIN["cases"][name]
        output=json.loads((root/name/"case_report.json").read_text())
        product=json.loads((root/name/"risu_product_diagnosis.json").read_text())
        result=output["mcp_call_result"]
        structured=result["structuredContent"]
        p=product["results"][0]
        assert output["original_http_status"]==200
        assert output["original_application_status_code"]==config["application_status_code"]
        assert p["source_http_status"]==200
        assert p["evidence_v1"]["error_flag"]=="ERROR_FLAG_MATCH"
        assert p["verdict"]=="LOSS"
        assert p["losses"]==["/result (missing)"]
        assert p["decision_v1"]["outcome"]=="REVIEW"
        assert p["causal_v1"]["outcome"]=="CONDITIONAL_MISMATCH"
        assert p["causal_v1"]["causal_level"]=="DEVELOPER_DECLARED_ONLY"
        assert product["causal_gate_v1"]["summary"]["CONFIRMED_LOSS"]==0
        assert result.get("isError",False) is False
        assert isinstance(structured,dict)
        if name=="normal":
            assert structured["items"] and len(structured["items"])==1
            assert structured["items"][0]["application_number"]==config["application_number"]
            assert structured["not_found"]==[]
            interpretation="KNOWN_JPO_APPLICATION_NUMBER_RETAINED_AFTER_SNAKE_CASE_NORMALIZATION"
        else:
            assert structured["items"]==[]
            assert structured["not_found"]==[config["application_number"]]
            assert "no data" in structured["summary"].lower()
            interpretation="KNOWN_JPO_APPLICATION_107_MAPPED_TO_TYPED_NOT_FOUND_NO_HTTP_ERROR"
        cases.append({"name":name,"original_http_status":200,
            "original_api_status_code":config["application_status_code"],
            "mcp_isError":False,"mcp_has_structuredContent":True,
            "adjudicated_case_specific_semantics":interpretation,
            "legacy_syntactic_result":p["verdict"],
            "legacy_syntactic_missing_field":"/result",
            "calibrated_decision":p["decision_v1"]["outcome"],
            "causal_gate":p["causal_v1"]["outcome"],
            "confirmed_loss":0,
            "unjustified_claim_prevented":"Legacy raw LOSS is not a certified semantic loss; original API envelope is intentionally mapped to a different MCP envelope.",
            "exact_source_application_status_code_survival":"NOT_PROVEN",
            "original_independent_mcp_wire":False})
    report={"schema":"risu-p4n-case-specific-original-vcr-to-real-stdio-mcp-qualifier-v1",
        "frozen_external_commit":PIN["original_commit"],
        "original_HTTP_cassettes_from_external_owner":2,
        "real_stdio_mcp_tool_calls_observed_by_RISU":2,
        "case_specific_semantics_preserved":2,
        "legacy_unverified_syntactic_LOSS":2,
        "calibrated_REVIEW":2,
        "causally_CONFIRMED_LOSS":0,
        "external_owner_originally_recorded_complete_dual_boundary":0,
        "independent_field_false_positive_rate":None,
        "cases":cases,
        "limitations":[
            "Semantic parity statements are restricted to the specific application-number and not-found mappings checked above, not all source fields.",
            "Original JPO status 107 is an application-level no-data result inside an HTTP 200 response. It is not an HTTP 404.",
            "RISU Probe v0.9.10 raw LOSS reports syntactic missing /result after intentional mapping; calibrated policy emits REVIEW and the causal gate blocks confirmation.",
            "The MCP stdio wire was generated by RISU replay using original third-party cassettes and source, not archived by the original developer.",
            "No full independent field false-positive rate can be computed from this cohort."
        ]}
    (root/"product_semantic_interpretation.json").write_text(json.dumps(report,sort_keys=True,indent=2)+"\n")
    return report

if __name__=="__main__":
    parser=argparse.ArgumentParser()
    parser.add_argument("--out",type=Path,default=ROOT/"results")
    args=parser.parse_args()
    r=qualify(args.out)
    print("P4N_CASE_SPECIFIC_SEMANTIC_PARITY_AUDIT_PASS",
          json.dumps({x:r[x] for x in (
              "case_specific_semantics_preserved","legacy_unverified_syntactic_LOSS",
              "calibrated_REVIEW","causally_CONFIRMED_LOSS",
              "external_owner_originally_recorded_complete_dual_boundary")},sort_keys=True),flush=True)
